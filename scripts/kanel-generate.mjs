// regenerates src/models from the dev database (see kanel.config.mjs).
// Post-processing after kanel runs:
// 1. Kanel ESM mode emits .js extensions; rewrite to .ts so imports match
//    actual file names and the repo's extensions-in-imports convention.
// 2. Enum-type files end with `export default X` for a type-only X, which
//    verbatimModuleSyntax rejects — rewrite to `export type { X as default }`.
// 3. Generate an index.ts barrel per schema folder (components import
//    from them; kanel deletes the whole output folder on regeneration).
import config from '../kanel.config.mjs'
import processDatabaseModule from 'kanel/build/processDatabase.js'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const processDatabase = processDatabaseModule.default || processDatabaseModule

try {
  await processDatabase(config)
} catch (error) {
  console.error(error)
  process.exit(1)
}

const outputPath = config.outputPath

async function rewriteJsToTs(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  await Promise.all(
    entries.map(async (entry) => {
      const fullPath = join(dir, entry.name)
      if (entry.isDirectory()) {
        await rewriteJsToTs(fullPath)
      } else if (entry.name.endsWith('.ts')) {
        const original = await readFile(fullPath, 'utf8')
        let updated = original.replace(
          /from ('|")(\.{1,2}\/[^'"]+)\.js\1/g,
          "from $1$2.ts$1",
        )
        // `export default X;` where X is a type alias (enums) is invalid
        // under verbatimModuleSyntax
        updated = updated.replace(
          /\nexport default (\w+);\n?$/,
          '\nexport type { $1 as default };\n',
        )
        if (updated !== original) await writeFile(fullPath, updated, 'utf8')
      }
    }),
  )
}

// wert-table code column types, kept from the former hand-maintained
// barrel — they model the wert-table code columns, which are plain strings
const barrelTypeDeclarations = {
  apflora: [
    'export type ApErfkritWerteCode = string',
    'export type ApqkQkName = string',
    'export type EkAbrechnungstypWerteCode = string',
    'export type PopStatusWerteCode = string',
    'export type TpopApberrelevantGrundWerteCode = string',
    'export type TpopEntwicklungWerteCode = string',
    'export type TpopStatusWerteCode = string',
    'export type TpopmassnErfbeurtWerteCode = string',
    'export type ZielTypWerteCode = string',
  ],
}

async function generateBarrel(dir, schemaName) {
  const files = (await readdir(dir)).filter((name) => name.endsWith('.ts'))
  const exports = await Promise.all(
    files
      .filter((file) => file !== 'index.ts')
      .map(async (file) => {
        const content = await readFile(join(dir, file), 'utf8')
        const names = [...content.matchAll(/^export type (\w+)/gm)].map(
          (m) => m[1],
        )
        const defaultInterface = content.match(
          /^export default interface (\w+)/m,
        )
        if (defaultInterface) names.push(`default as ${defaultInterface[1]}`)
        return names.length ?
            `export type { ${names.join(', ')} } from './${file}'`
          : null
      }),
  )
  const barrel = [
    '// generated by scripts/kanel-generate.mjs — do not modify manually',
    ...exports.filter(Boolean),
    '',
    ...(barrelTypeDeclarations[schemaName] ?? []),
    '',
  ].join('\n')
  await writeFile(join(dir, 'index.ts'), barrel, 'utf8')
}

await rewriteJsToTs(outputPath)
const schemaDirs = (
  await readdir(outputPath, { withFileTypes: true })
).filter((e) => e.isDirectory())
await Promise.all(
  schemaDirs.map((e) => generateBarrel(join(outputPath, e.name), e.name)),
)
console.log(`models generated in ${outputPath}`)
